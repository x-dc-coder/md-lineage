/** True when github-slugger keeps the code point (a lone surrogate never is). */
function kept(code: number): boolean {
  // github-slugger's removal list names BMP code points and whole surrogate
  // PAIRS, so a lone half is not on the list and `slug()` echoes it back when
  // fed one directly — but a lone half never appears in a heading except as
  // the broken remainder of a split emoji, and GitHub drops it. The table
  // stops at U+D7FB and resumes at U+F900; a caller that reads the table one
  // UTF-16 UNIT at a time would therefore drop every astral character (its
  // high surrogate is in the gap), which is why `slugifyHeading` iterates
  // code POINTS and only a truly unpaired half reaches this branch.
  if (code >= 0xd800 && code <= 0xdfff) return false;
  // Binary search over the table: the ranges are sorted and disjoint, so a
  // probe costs O(log R) and the whole slug costs O(len · log R).
  let lo = 0;
  let hi = KEPT_RANGES.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >>> 1;
    const range = KEPT_RANGES[mid]!;
    if (code < range.lo) hi = mid - 1;
    else if (code > range.hi) lo = mid + 1;
    else return true;
  }
  return false;
}

/**
 * Base slug without duplicate handling. Unicode letters (CJK etc.) are kept.
 *
 * Filtering and hyphenation are one pass over the lowercased string: a space
 * maps to '-', every other KEPT code point maps to itself, and everything else
 * (punctuation such as ',' '&' '+' '.', or an emoji) is dropped. The walk is
 * by CODE POINT, not by UTF-16 unit, because a surrogate half is what a split
 * astral character leaves behind and it must not reach the table — `kept()`
 * would otherwise classify a valid character's high surrogate as a gap. Doing
 * the filter and the hyphenation in one pass is the point: filtering first and
 * then hyphenating the UNFILTERED string is how "Hello, World!" used to anchor
 * as "hello,-world!" instead of GitHub's "hello-world".
 */
export function slugifyHeading(text: string): string {
  const lower = text.toLowerCase();
  let out = '';
  for (const ch of lower) {
    const code = ch.codePointAt(0)!;
    if (code === 0x20) {
      out += '-';
      continue;
    }
    if (kept(code)) out += ch;
  }
  return out;
}

/**
 * Per-document slugger: returns the anchor as authored in an `evidence` value
 * (without the leading `#`), appending GitHub's `-n` suffix when the same base
 * slug appears more than once in the document.
 */
export class Slugger {
  private readonly counts = new Map<string, number>();

  /** Register a heading and get its anchor (no leading `#`). */
  slug(text: string): string {
    const base = slugifyHeading(text);
    const count = this.counts.get(base) ?? 0;
    this.counts.set(base, count + 1);
    return count === 0 ? base : `${base}-${count}`;
  }

  /** Every anchor the document produces, for membership tests. */
  anchors(): Set<string> {
    const out = new Set<string>();
    for (const [base, count] of this.counts) {
      out.add(base);
      // GitHub's repeat headings get -1, -2, … anchors; evidence may cite them.
      for (let n = 1; n < count; n++) out.add(`${base}-${n}`);
    }
    return out;
  }
}
