/**
 * GFM heading slug generation (docs/remark-language-server-solution.md §14.1:
 * "GFM slug、重复 heading、Unicode heading").
 *
 * Implements the github-slugger algorithm:
 *   1. lowercase (Unicode-aware, so a Chinese heading keeps its characters);
 *   2. drop every code point on github-slugger's removal list — punctuation,
 *      symbols, control characters, and the surrogate halves of emoji — while
 *      letters, numbers, hyphens, underscores and spaces survive;
 *   3. replace each surviving ASCII space with a hyphen (runs are NOT
 *      collapsed: "## A  B" anchors as "a--b"; a tab is dropped, not
 *      hyphenated, because github-slugger's second pass is / /g).
 *
 * Step 2's table is the exact complement of github-slugger 2.0.0's removal
 * list: it was derived by classifying every code point in 0..0x10FFFF with the
 * package itself, and is pinned by
 * `packages/validator/test/slug-parity.test.ts` against the real package. It is
 * NOT a Unicode-category approximation — the removal list is a curated
 * blacklist, so it keeps symbols a category test would drop and drops letters a
 * category test would keep (U+02C2–U+02C5 are Unicode letters but removed).
 *
 * GitHub additionally appends a numeric suffix when a slug repeats within one
 * document; `Slugger` below keeps a per-document counter so the second
 * `## Notes` becomes `notes-1`.
 */

